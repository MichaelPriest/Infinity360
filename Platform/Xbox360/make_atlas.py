"""Rebuild the console's RGB(A) artwork and glyph atlas from the dashboard art."""
import argparse
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parent
parser = argparse.ArgumentParser()
parser.add_argument("font", help="Path to DejaVuSans.ttf")
args = parser.parse_args()
font = ImageFont.truetype(args.font, 22)
atlas = Image.new("RGBA", (1024, 512))
art = root.parents[1] / "Web/art"
placements = [
    ("library.jpg", 0, 0, 342, 222), ("television.jpg", 344, 0, 254, 222),
    ("controls.png", 600, 0, 208, 52), ("mark.jpg", 814, 0, 64, 64),
    ("racing.jpg", 600, 66, 140, 64), ("scifi.jpg", 742, 66, 140, 64),
    ("action.jpg", 600, 132, 140, 64)
]
for name, x, y, w, h in placements:
    with Image.open(art / name) as im:
        image = im.convert("RGBA").resize((w, h), Image.Resampling.LANCZOS)
        if name in ("library.jpg", "television.jpg"):
            edge = Image.new("L", (w, h))
            edge.putdata([min(255, 17*min(i, j, w-1-i, h-1-j)) for j in range(h) for i in range(w)])
            image.putalpha(edge)
        atlas.paste(image, (x, y))
draw = ImageDraw.Draw(atlas)
widths = []
for glyph in range(32, 256):
    x, y = ((glyph-32) % 32)*30, 234+((glyph-32)//32)*34
    char = chr(glyph) if chr(glyph).isprintable() else "?"
    draw.text((x, y+25), char, font=font, anchor="ls", fill="white")
    widths.append(round(font.getlength(char)))
atlas.save(root / "Assets/home.tga", compression="tga_rle")
(root / "GlyphWidths.h").write_text("// Generated by make_atlas.py from DejaVu Sans.\n"
    "static const unsigned char glyphWidths[224] = {\n" +
    "".join("    " + ", ".join(map(str, widths[i:i+16])) + ",\n" for i in range(0, len(widths), 16)) + "};\n")
