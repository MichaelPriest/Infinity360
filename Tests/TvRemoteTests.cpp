#include "TvRemoteProtocol.h"
#include "TvRemoteCatalog.h"
#include "TvRemoteDiscovery.h"
int main(){
    using namespace TvRemote;
    const std::string host="192.168.1.4:32161",key="0123456789abcdef0123456789abcdef";
    const auto request=[&](const std::string& command,const std::string& token,const std::string& h){return "POST /cmd/"+command+" HTTP/1.1\r\nHost: "+h+"\r\nX-Infinity-Key: "+token+"\r\nContent-Length: 0\r\n\r\n";};
    if(!ValidSecret(key)||ValidSecret("1234"))return 1;
    if(!Parse("GET / HTTP/1.1\r\nHost: "+host+"\r\n\r\n",host,key).page)return 2;
    if(Parse(request("quality",key,host),host,key).key!=Key::Quality)return 3;
    if(Parse(request("quality","wrong",host),host,key).key!=Key::None)return 4;
    if(Parse(request("quality",key,"other"),host,key).key!=Key::None)return 5;
    if(Parse(request("launch",key,host),host,key).key!=Key::None)return 6;
    if(Parse(request("mute",key,host)+"body",host,key).key!=Key::None)return 7;
    if(Parse(request("mute",key,host),host,key).key!=Key::Mute)return 8;
    if(Parse(request("status",key,host),host,key).key!=Key::Status)return 9;
    if(Parse(request("guide",key,host),host,key).key!=Key::Guide)return 10;
    if(Parse(request("favorite",key,host),host,key).key!=Key::Favorite)return 11;
    if(Parse(request("power",key,host),host,key).key!=Key::None)return 12;
    if(Parse(request("snapshot",key,host),host,key).key!=Key::Snapshot)return 13;
    if(Parse(request("snapshot","wrong",host),host,key).key!=Key::None)return 14;
    const auto page=Parse(request("tv/16/6162",key,host),host,key);
    if(page.key!=Key::TvCatalog||page.offset!=16||page.query!="ab")return 15;
    if(Parse(request("games/0/ffx",key,host),host,key).key!=Key::None)return 16;
    if(Parse(request("games/0/", "wrong",host),host,key).key!=Key::None)return 17;
    if(Quote("a\"b\\c")!="\"a\\\"b\\\\c\"")return 18;
    const auto list=CatalogPage(20,0,[](size_t){return std::string("{}");});
    if(list.find("\"next\":16")==std::string::npos)return 19;
    if(!Matches("ABC","ab"))return 20;
    if(Parse(request("tune/18446744073709551615",key,host),host,key).key!=Key::Tune)return 21;
    if(Parse(request("tune/18446744073709551616",key,host),host,key).key!=Key::None)return 22;
    if(Parse(request("tune/0",key,host),host,key).key!=Key::None)return 23;
    if(Parse(request("tune/1","wrong",host),host,key).key!=Key::None)return 24;
    if(Parse(request("logo/1",key,host),host,key).key!=Key::Logo)return 25;
    if(Parse(request("logo/../file",key,host),host,key).key!=Key::None)return 26;
    if(Parse(request("logo/1","wrong",host),host,key).key!=Key::None)return 27;
    if(Parse(request("cover/1",key,host),host,key).key!=Key::Cover)return 28;
    if(Parse(request("cover/../x",key,host),host,key).key!=Key::None)return 29;
    if(Parse(request("cover/1","wrong",host),host,key).key!=Key::None)return 30;
    if(GameArtId("game:/a")==GameArtId("game:/b")||GameArtId("game:/a")!=GameArtId("game:/a"))return 31;
    if(CoverThumbnail("")!="{\"available\":false}")return 32;
    if(Parse(request("downloads",key,host),host,key).key!=Key::Downloads)return 33;
    if(Parse(request("downloads","wrong",host),host,key).key!=Key::None)return 34;
    const std::string nonce="fedcba9876543210fedcba9876543210",ip="192.168.1.4";
    const auto msg=DiscoveryMessage(nonce,ip);
    if(DiscoveryReply("INFINITY360-DISCOVER/1 "+nonce,ip,key)!=msg+" "+DiscoveryMac(key,msg))return 35;
    if(!DiscoveryReply("INFINITY360-DISCOVER/1 invalid",ip,key).empty())return 36;
    if(DiscoveryMac(key,msg)==DiscoveryMac(key,msg+"x"))return 37;
    if(DiscoveryMac("wrong",msg)!="")return 38;
    if(Parse(request("store/0/67616d65",key,host),host,key).key!=Key::Store)return 39;
    if(Parse(request("storedownload/1",key,host),host,key).key!=Key::StoreDownload)return 40;
    if(Parse(request("storequeue/1",key,host),host,key).key!=Key::StoreQueue)return 41;
    if(Parse(request("storedownload/../x",key,host),host,key).key!=Key::None)return 42;
    if(Parse(request("storequeue/1","wrong",host),host,key).key!=Key::None)return 43;
    if(Parse(request("storestart",key,host),host,key).key!=Key::StoreStart)return 44;
    if(Parse(request("storepause",key,host),host,key).key!=Key::StorePause)return 45;
    if(Parse(request("storeremove/1",key,host),host,key).key!=Key::StoreRemove)return 46;
    if(Parse(request("storeremove/0",key,host),host,key).key!=Key::None)return 47;
    if(Parse(request("storepause","wrong",host),host,key).key!=Key::None)return 48;
    if(Parse(request("storestart/1",key,host),host,key).key!=Key::None)return 49;
    if(Parse(request("storedevices",key,host),host,key).key!=Key::StoreDevices)return 50;
    if(Parse(request("storedevice/usb1",key,host),host,key).query!="usb1")return 51;
    if(Parse(request("storedevice/../x",key,host),host,key).key!=Key::None)return 52;
    if(Parse(request("storedevice/usb3",key,host),host,key).key!=Key::None)return 53;
    if(Parse(request("storepriority/1",key,host),host,key).key!=Key::StorePriority)return 54;
    if(Parse(request("storepriority/1","wrong",host),host,key).key!=Key::None)return 55;
    if(Parse(request("storeinstall/1",key,host),host,key).key!=Key::StoreInstallReview)return 56;
    if(Parse(request("storeinstall/0",key,host),host,key).key!=Key::None)return 57;
    if(Parse(request("storeinstall/1","wrong",host),host,key).key!=Key::None)return 58;
    if(Parse(request("storeinstall/../x",key,host),host,key).key!=Key::None)return 59;
    return 0;
}
